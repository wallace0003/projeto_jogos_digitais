        static Dictionary<char, string[]> todos;

        /// <summary>Todos os glifos, já com as <see cref="AlturaGlifo"/> linhas.</summary>
        public static Dictionary<char, string[]> Todos()
        {
            if (todos != null)
                return todos;
            var d = new Dictionary<char, string[]>();
            foreach (KeyValuePair<char, string[]> par in Maiusculas)
                d[par.Key] = Completar(par.Value, LinhaTopo);
            foreach (KeyValuePair<char, string[]> par in Minusculas)
                d[par.Key] = Completar(par.Value, LinhaTopo);
            foreach (string comp in Compostas)
            {
                char letra = comp[0];
                char baseLetra = comp[2];
                char acento = comp[4];
                string[] b = d[baseLetra];
                d[letra] = Acentuar(b, Acentos[acento], char.IsUpper(baseLetra));
            }
            // "í": o pingo do i vira acento
            d['í'] = Completar(new[] { "..#", ".#.", "##.", ".#.", ".#.", ".#.", "###", "...", "..." }, LinhaTopo);
            todos = d;
            return d;
        }

        static string[] Completar(string[] linhas, int inicio)
        {
            int largura = 0;
            foreach (string l in linhas)
                largura = System.Math.Max(largura, l.Length);
            var r = new string[AlturaGlifo];
            for (int i = 0; i < AlturaGlifo; i++)
            {
                int j = i - inicio;
                string l = j >= 0 && j < linhas.Length ? linhas[j] : "";
                r[i] = l.PadRight(largura, '.');
            }
            return r;
        }

        /// <summary>Coloca o acento acima da letra (maiúscula: nas linhas 0-1; minúscula: nas linhas 2-3).</summary>
        static string[] Acentuar(string[] letra, string[] acento, bool maiuscula)
        {
            var r = (string[])letra.Clone();
            int largura = r[0].Length;
            int linha = maiuscula ? 0 : LinhaTopo;
            for (int i = 0; i < 2; i++)
            {
                string a = acento[i];
                // centraliza o acento (largura 5) na letra
                int desloc = (largura - a.Length) / 2;
                char[] atual = r[linha + i].ToCharArray();
                for (int k = 0; k < a.Length; k++)
                {
                    int x = k + desloc;
                    if (x >= 0 && x < largura && a[k] == '#')
                        atual[x] = '#';
                }
                r[linha + i] = new string(atual);
            }
            return r;
        }

        public static bool Existe(char c)
        {
            return Todos().ContainsKey(c);
        }

        /// <summary>Converte o caractere para um que exista na fonte ('?' se não houver parecido).</summary>
        public static char Normalizar(char c)
        {
            if (c == ' ' || c == '\n' || Existe(c))
                return c;
            switch (c)
            {
                case 'È': return 'É';
                case 'Ì': case 'Î': case 'Ï': return 'I';
                case 'Ò': return 'Ó';
                case 'Ù': case 'Û': return 'Ú';
                case 'Ä': return 'A';
                case 'Ë': return 'E';
                case 'Ö': return 'O';
                case 'è': return 'é';
                case 'ì': case 'î': case 'ï': return 'í';
                case 'ò': return 'ó';
                case 'ù': case 'û': return 'ú';
                case 'ä': return 'a';
                case 'ë': return 'e';
                case 'ö': return 'o';
                case '–': case '—': return '-';
                case '“': case '”': return '"';
                case '‘': case '’': return '\'';
                case '…': return '.';
            }
            return '?';
        }

        /// <summary>O texto pode ser escrito sem nenhum '?' de substituição?</summary>
        public static bool TextoSuportado(string texto, out char faltando)
        {
            faltando = '\0';
            foreach (char c in texto ?? "")
            {
                if (c == '?')
                    continue;
                if (Normalizar(c) == '?')
                {
                    faltando = c;
                    return false;
                }
            }
            return true;
        }
